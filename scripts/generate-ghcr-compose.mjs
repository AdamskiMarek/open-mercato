#!/usr/bin/env node
// Derives docker-compose.fullapp.ghcr.yml from docker-compose.fullapp.yml.
// The fork's VPS is too small to build the fullapp image, so the
// `.github/workflows/ghcr-image.yml` workflow builds it in GitHub Actions and
// pushes it to GHCR. This pull-only compose variant is otherwise identical to
// the fullapp compose: the app service drops its `build:` section, and every
// service that ran the locally built `open-mercato/app` image pulls the GHCR
// image instead, with `pull_policy: always` so a moving tag (latest) is re-pulled.
//
//   node scripts/generate-ghcr-compose.mjs          # (re)write the file
//   node scripts/generate-ghcr-compose.mjs --check  # exit 1 when it drifted
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
export const SOURCE = 'docker-compose.fullapp.yml'
export const TARGET = 'docker-compose.fullapp.ghcr.yml'
export const GHCR_IMAGE = 'ghcr.io/adamskimarek/open-mercato-app:${OM_IMAGE_TAG:-latest}'
const LOCAL_IMAGE_LINE = '    image: open-mercato/app:${DEPLOY_ENV:-local}\n'

const HEADER = `# Pull-only variant of ${SOURCE} for the AdamskiMarek/open-mercato fork.
# GENERATED by scripts/generate-ghcr-compose.mjs — do not edit by hand; edit
# ${SOURCE} (or starters/docker/compose.fullapp.yml) and regenerate.
# The app image is built by .github/workflows/ghcr-image.yml and pulled from
# GHCR (OM_IMAGE_TAG selects the tag: latest | develop_OM_CRM | sha-<short>).

`

export function transformCompose(source) {
  // Drop the leading comment block (the back-compat header of the root duplicate).
  const body = source.replace(/^(#[^\n]*\n|\s*\n)+/, '')

  const buildStart = body.indexOf('  app:\n    build:\n')
  if (buildStart === -1) throw new Error('[ghcr-compose] app service build section not found')
  const buildBodyStart = buildStart + '  app:\n'.length
  const buildEnd = body.indexOf(LOCAL_IMAGE_LINE, buildBodyStart)
  if (buildEnd === -1) throw new Error('[ghcr-compose] app image line not found after build section')
  let out = body.slice(0, buildBodyStart) + body.slice(buildEnd)

  const occurrences = out.split(LOCAL_IMAGE_LINE).length - 1
  if (occurrences < 1) throw new Error('[ghcr-compose] no open-mercato/app image references found')
  out = out.split(LOCAL_IMAGE_LINE).join(`    image: ${GHCR_IMAGE}\n    pull_policy: always\n`)
  if (out.includes('open-mercato/app:')) throw new Error('[ghcr-compose] unexpected open-mercato/app reference left')
  return HEADER + out
}

function main() {
  const source = fs.readFileSync(path.join(ROOT, SOURCE), 'utf8')
  const expected = transformCompose(source)
  const targetPath = path.join(ROOT, TARGET)
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(targetPath) ? fs.readFileSync(targetPath, 'utf8') : ''
    if (current !== expected) {
      console.error(`${TARGET} is out of date — run: node scripts/generate-ghcr-compose.mjs`)
      process.exit(1)
    }
    console.log(`${TARGET} is up to date`)
    return
  }
  fs.writeFileSync(targetPath, expected)
  console.log(`Wrote ${TARGET}`)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main()
